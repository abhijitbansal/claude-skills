const draws = (seed, count) => {
  const rng = mulberry32(seed);
  return Array.from({ length: count }, () => rng());
};

test('the engine mulberry32 draws the numbers version 1 drew: the first twenty for seeds 1, 7 and 7918', () => {
  for (const [seed, expected] of Object.entries(RECORDED)) assert.deepEqual(draws(Number(seed), 20), expected, `seed ${seed}`);
});

test('a different seed draws a different stream', () => {
  assert.notDeepEqual(draws(1, 10), draws(2, 10));
});
